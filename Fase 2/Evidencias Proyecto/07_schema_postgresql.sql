-- CogniStock: esquema de base de datos (PostgreSQL)
-- Es el mismo modelo definido en Backend/api/models.py. En el proyecto las tablas
-- se crean con "python manage.py migrate"; este script sirve como referencia.

-- Seguridad y administración

CREATE TABLE roles (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(50)  NOT NULL UNIQUE,
    descripcion VARCHAR(255) NOT NULL DEFAULT ''
);

-- La contraseña se guarda como hash generado por Django.
CREATE TABLE usuarios (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(120) NOT NULL,
    email        VARCHAR(150) NOT NULL UNIQUE,
    password     VARCHAR(128) NOT NULL,
    rol_id       BIGINT       NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    activo       BOOLEAN      NOT NULL DEFAULT TRUE,
    is_staff     BOOLEAN      NOT NULL DEFAULT FALSE,
    is_superuser BOOLEAN      NOT NULL DEFAULT FALSE,
    last_login   TIMESTAMPTZ,
    creado_en    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE permisos (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo      VARCHAR(60)  NOT NULL UNIQUE,
    descripcion VARCHAR(255) NOT NULL DEFAULT ''
);

CREATE TABLE rol_permisos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id     BIGINT NOT NULL REFERENCES roles(id)    ON DELETE CASCADE,
    permiso_id BIGINT NOT NULL REFERENCES permisos(id) ON DELETE CASCADE,
    CONSTRAINT uq_rol_permiso UNIQUE (rol_id, permiso_id)
);

CREATE TABLE parametros_sistema (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave              VARCHAR(80)  NOT NULL UNIQUE,
    valor              VARCHAR(255) NOT NULL,
    descripcion        VARCHAR(255) NOT NULL DEFAULT '',
    actualizado_por_id BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    actualizado_en     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE bitacora_auditoria (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT REFERENCES usuarios(id) ON DELETE RESTRICT,
    accion     VARCHAR(50) NOT NULL,
    entidad    VARCHAR(50) NOT NULL,
    entidad_id BIGINT,
    detalle    JSONB,
    ip         INET,
    fecha      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_bitacora_entidad ON bitacora_auditoria(entidad, entidad_id);
CREATE INDEX idx_bitacora_fecha   ON bitacora_auditoria(fecha DESC);

-- Productos y proveedores

CREATE TABLE categorias_producto (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(255) NOT NULL DEFAULT '',
    activo      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE productos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo            VARCHAR(80)  NOT NULL UNIQUE,
    codigo_qr         VARCHAR(255) UNIQUE,
    nombre            VARCHAR(150) NOT NULL,
    descripcion       TEXT         NOT NULL DEFAULT '',
    categoria_id      BIGINT REFERENCES categorias_producto(id) ON DELETE RESTRICT,
    unidad_medida     VARCHAR(30)  NOT NULL DEFAULT 'unidad',
    precio_referencia NUMERIC(12,2) NOT NULL DEFAULT 0,
    stock_minimo      NUMERIC(12,2) NOT NULL DEFAULT 0,
    activo            BOOLEAN      NOT NULL DEFAULT TRUE,
    creado_en         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_producto_precio_ref    CHECK (precio_referencia >= 0),
    CONSTRAINT ck_producto_stock_minimo  CHECK (stock_minimo >= 0)
);

CREATE TABLE datos_producto_externo (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id         BIGINT       NOT NULL REFERENCES productos(id) ON DELETE CASCADE,
    fuente              VARCHAR(50)  NOT NULL,
    codigo_barras       VARCHAR(80)  NOT NULL DEFAULT '',
    marca               VARCHAR(150) NOT NULL DEFAULT '',
    descripcion_externa TEXT         NOT NULL DEFAULT '',
    imagen_url          VARCHAR(500) NOT NULL DEFAULT '',
    datos               JSONB,
    consultado_en       TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_dato_externo_producto_fuente UNIQUE (producto_id, fuente)
);

CREATE TABLE proveedores (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR(150) NOT NULL,
    rut      VARCHAR(30)  NOT NULL DEFAULT '',
    email    VARCHAR(150) NOT NULL DEFAULT '',
    telefono VARCHAR(30)  NOT NULL DEFAULT '',
    activo   BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE proveedor_producto (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id     BIGINT NOT NULL REFERENCES proveedores(id) ON DELETE CASCADE,
    producto_id      BIGINT NOT NULL REFERENCES productos(id)   ON DELETE CASCADE,
    codigo_proveedor VARCHAR(80) NOT NULL DEFAULT '',
    ultimo_precio    NUMERIC(12,2),
    CONSTRAINT uq_proveedor_producto        UNIQUE (proveedor_id, producto_id),
    CONSTRAINT ck_proveedor_producto_precio CHECK (ultimo_precio >= 0)
);

-- Cotizaciones

CREATE TABLE monedas (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(3)  NOT NULL UNIQUE,
    nombre  VARCHAR(50) NOT NULL,
    simbolo VARCHAR(5)  NOT NULL DEFAULT ''
);

-- permite_entrada indica qué estados habilitan registrar una entrada.
CREATE TABLE estados_cotizacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo          VARCHAR(30)  NOT NULL UNIQUE,
    descripcion     VARCHAR(255) NOT NULL DEFAULT '',
    permite_entrada BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE cotizaciones (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id  BIGINT      NOT NULL REFERENCES proveedores(id)        ON DELETE RESTRICT,
    numero        VARCHAR(60) NOT NULL UNIQUE,
    moneda_id     BIGINT      NOT NULL REFERENCES monedas(id)            ON DELETE RESTRICT,
    estado_id     BIGINT      NOT NULL REFERENCES estados_cotizacion(id) ON DELETE RESTRICT,
    fecha         DATE        NOT NULL DEFAULT CURRENT_DATE,
    observaciones TEXT        NOT NULL DEFAULT '',
    creado_por_id BIGINT      NOT NULL REFERENCES usuarios(id)           ON DELETE RESTRICT,
    creado_en     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_cotizaciones_proveedor ON cotizaciones(proveedor_id);

CREATE TABLE detalle_cotizacion (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id   BIGINT NOT NULL REFERENCES cotizaciones(id) ON DELETE CASCADE,
    producto_id     BIGINT NOT NULL REFERENCES productos(id)    ON DELETE RESTRICT,
    cantidad        NUMERIC(12,2) NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    CONSTRAINT uq_detalle_cotizacion_producto UNIQUE (cotizacion_id, producto_id),
    CONSTRAINT ck_detalle_cotizacion_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_cotizacion_precio   CHECK (precio_unitario >= 0)
);
CREATE INDEX idx_detalle_cotizacion_prod ON detalle_cotizacion(producto_id);

CREATE TABLE historial_estado_cotizacion (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id      BIGINT NOT NULL REFERENCES cotizaciones(id)       ON DELETE CASCADE,
    estado_anterior_id BIGINT          REFERENCES estados_cotizacion(id) ON DELETE RESTRICT,
    estado_nuevo_id    BIGINT NOT NULL REFERENCES estados_cotizacion(id) ON DELETE RESTRICT,
    usuario_id         BIGINT NOT NULL REFERENCES usuarios(id)           ON DELETE RESTRICT,
    motivo             TEXT        NOT NULL DEFAULT '',
    fecha              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Inventario, entradas y salidas

CREATE TABLE stock (
    producto_id    BIGINT PRIMARY KEY REFERENCES productos(id) ON DELETE CASCADE,
    cantidad       NUMERIC(12,2) NOT NULL DEFAULT 0,
    actualizado_en TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_stock_no_negativo CHECK (cantidad >= 0)
);

CREATE TABLE entradas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cotizacion_id BIGINT NOT NULL REFERENCES cotizaciones(id) ON DELETE RESTRICT,
    usuario_id    BIGINT NOT NULL REFERENCES usuarios(id)     ON DELETE RESTRICT,
    fecha         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observaciones TEXT        NOT NULL DEFAULT ''
);

CREATE TABLE detalle_entrada (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entrada_id  BIGINT NOT NULL REFERENCES entradas(id)  ON DELETE CASCADE,
    producto_id BIGINT NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
    cantidad    NUMERIC(12,2) NOT NULL,
    CONSTRAINT ck_detalle_entrada_cantidad CHECK (cantidad > 0)
);

CREATE TABLE salidas (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    fecha         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observaciones TEXT        NOT NULL DEFAULT ''
);

CREATE TABLE detalle_salida (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    salida_id   BIGINT NOT NULL REFERENCES salidas(id)   ON DELETE CASCADE,
    producto_id BIGINT NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
    cantidad    NUMERIC(12,2) NOT NULL,
    codigo_qr   VARCHAR(255)  NOT NULL DEFAULT '',
    CONSTRAINT ck_detalle_salida_cantidad CHECK (cantidad > 0)
);

-- Cada movimiento apunta a la entrada o a la salida que lo generó.
CREATE TABLE movimientos (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id   BIGINT NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
    usuario_id    BIGINT NOT NULL REFERENCES usuarios(id)  ON DELETE RESTRICT,
    tipo          VARCHAR(20)   NOT NULL,
    cantidad      NUMERIC(12,2) NOT NULL,
    entrada_id    BIGINT REFERENCES entradas(id) ON DELETE RESTRICT,
    salida_id     BIGINT REFERENCES salidas(id)  ON DELETE RESTRICT,
    fecha         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observaciones TEXT        NOT NULL DEFAULT '',
    CONSTRAINT ck_movimiento_tipo       CHECK (tipo IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT ck_movimiento_cantidad   CHECK (cantidad > 0),
    CONSTRAINT ck_movimiento_referencia CHECK (
        (tipo = 'ENTRADA' AND entrada_id IS NOT NULL AND salida_id IS NULL) OR
        (tipo = 'SALIDA'  AND salida_id  IS NOT NULL AND entrada_id IS NULL)
    )
);
CREATE INDEX idx_movimientos_producto_fecha ON movimientos(producto_id, fecha DESC);

-- Se guarda cada lectura de QR, también las rechazadas.
CREATE TABLE escaneos_qr (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_leido VARCHAR(255) NOT NULL,
    producto_id  BIGINT          REFERENCES productos(id) ON DELETE RESTRICT,
    usuario_id   BIGINT NOT NULL REFERENCES usuarios(id)  ON DELETE RESTRICT,
    resultado    VARCHAR(20)  NOT NULL,
    salida_id    BIGINT          REFERENCES salidas(id)   ON DELETE RESTRICT,
    fecha        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_escaneo_resultado CHECK (resultado IN ('OK', 'SIN_STOCK', 'QR_INVALIDO'))
);

CREATE TABLE alertas_stock (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id         BIGINT NOT NULL REFERENCES productos(id) ON DELETE RESTRICT,
    tipo                VARCHAR(20)   NOT NULL,
    cantidad_al_generar NUMERIC(12,2) NOT NULL,
    estado              VARCHAR(20)   NOT NULL DEFAULT 'ACTIVA',
    atendida_por_id     BIGINT REFERENCES usuarios(id) ON DELETE RESTRICT,
    creada_en           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atendida_en         TIMESTAMPTZ,
    CONSTRAINT ck_alerta_tipo   CHECK (tipo IN ('STOCK_BAJO', 'SIN_STOCK')),
    CONSTRAINT ck_alerta_estado CHECK (estado IN ('ACTIVA', 'ATENDIDA'))
);
-- Solo puede haber una alerta activa por producto y tipo.
CREATE UNIQUE INDEX uq_alerta_activa_producto_tipo
    ON alertas_stock(producto_id, tipo) WHERE estado = 'ACTIVA';

-- Integraciones externas

CREATE TABLE tipos_cambio (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moneda_origen_id  BIGINT NOT NULL REFERENCES monedas(id) ON DELETE RESTRICT,
    moneda_destino_id BIGINT NOT NULL REFERENCES monedas(id) ON DELETE RESTRICT,
    valor             NUMERIC(18,6) NOT NULL,
    fecha             DATE          NOT NULL,
    fuente            VARCHAR(50)   NOT NULL DEFAULT 'Frankfurter',
    consultado_en     TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tipo_cambio_dia               UNIQUE (moneda_origen_id, moneda_destino_id, fecha),
    CONSTRAINT ck_tipo_cambio_valor             CHECK (valor > 0),
    CONSTRAINT ck_tipo_cambio_monedas_distintas CHECK (moneda_origen_id <> moneda_destino_id)
);

CREATE TABLE feriados (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha  DATE         NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    pais   VARCHAR(2)   NOT NULL DEFAULT 'CL',
    CONSTRAINT uq_feriado_fecha_pais UNIQUE (fecha, pais)
);

CREATE TABLE llamadas_api_externa (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    servicio      VARCHAR(20)  NOT NULL,
    endpoint      VARCHAR(500) NOT NULL,
    metodo        VARCHAR(10)  NOT NULL DEFAULT 'GET',
    estado_http   SMALLINT,
    exito         BOOLEAN      NOT NULL,
    mensaje_error TEXT         NOT NULL DEFAULT '',
    duracion_ms   INTEGER,
    usuario_id    BIGINT REFERENCES usuarios(id) ON DELETE SET NULL,
    fecha         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_llamada_api_servicio CHECK (servicio IN ('FRANKFURTER', 'NAGER_DATE', 'PRODUCTOS', 'GROQ'))
);
CREATE INDEX idx_llamadas_api_servicio ON llamadas_api_externa(servicio, fecha DESC);

-- Agente de IA

CREATE TABLE conversaciones_agente (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id    BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
    pregunta      TEXT         NOT NULL,
    respuesta     TEXT         NOT NULL DEFAULT '',
    modelo        VARCHAR(100) NOT NULL DEFAULT '',
    tokens_usados INTEGER,
    fecha         TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ejecuciones_tool_agente (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversacion_id BIGINT NOT NULL REFERENCES conversaciones_agente(id) ON DELETE CASCADE,
    tool            VARCHAR(80) NOT NULL,
    parametros      JSONB       NOT NULL DEFAULT '{}',
    resultado       JSONB,
    permitido       BOOLEAN     NOT NULL,
    motivo_rechazo  TEXT        NOT NULL DEFAULT '',
    fecha           TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- El agente solo propone; una persona acepta o descarta.
CREATE TABLE recomendaciones_reposicion (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id           BIGINT NOT NULL REFERENCES productos(id)           ON DELETE RESTRICT,
    proveedor_sugerido_id BIGINT          REFERENCES proveedores(id)         ON DELETE RESTRICT,
    cantidad_sugerida     NUMERIC(12,2) NOT NULL,
    justificacion         TEXT          NOT NULL,
    estado                VARCHAR(20)   NOT NULL DEFAULT 'PROPUESTA',
    conversacion_id       BIGINT          REFERENCES conversaciones_agente(id) ON DELETE SET NULL,
    revisada_por_id       BIGINT          REFERENCES usuarios(id)            ON DELETE RESTRICT,
    creada_en             TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revisada_en           TIMESTAMPTZ,
    CONSTRAINT ck_recomendacion_cantidad CHECK (cantidad_sugerida > 0),
    CONSTRAINT ck_recomendacion_estado   CHECK (estado IN ('PROPUESTA', 'ACEPTADA', 'DESCARTADA'))
);

